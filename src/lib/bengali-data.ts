for (const [k, v] of Object.entries(BENGALI_MOSHAFS)) {
  LOWER_BENGALI_MOSHAFS.set(k.toLowerCase().trim(), v);
}

export function getLocalizedMoshafName(name: string, locale?: string): string {
  if (locale !== "bn") return name;
  const trimmed = name.trim();
  const direct = BENGALI_MOSHAFS[trimmed];
  if (direct) return direct;

  const lower = trimmed.toLowerCase();
  const fromLower = LOWER_BENGALI_MOSHAFS.get(lower);
  if (fromLower) return fromLower;

  const norm = lower.replace(/[^a-z0-9]/g, " ").replace(/\s+/g, " ").trim();
  for (const [k, v] of LOWER_BENGALI_MOSHAFS.entries()) {
    const kNorm = k.replace(/[^a-z0-9]/g, " ").replace(/\s+/g, " ").trim();
    if (kNorm === norm) return v;
  }

  // Component fallback if split by comma
  if (trimmed.includes(",")) {
    const parts = trimmed.split(",").map((p) => p.trim());
    const localizedParts = parts.map((p) => getLocalizedMoshafName(p, locale));
    if (localizedParts.some((p, i) => p !== parts[i])) {
      return localizedParts.join(", ");
    }
  }

  return name;
}
