const BN_DIGITS = ["০", "১", "২", "৩", "৪", "৫", "৬", "৭", "৮", "৯"];

export function toBengaliDigits(num: number | string): string {
  return String(num).replace(/[0-9]/g, (d) => BN_DIGITS[Number(d)] ?? d);
}

export function fromBengaliDigits(str: string): string {
  return str.replace(/[০-৯]/g, (ch) => String(BN_DIGITS.indexOf(ch)));
}

export function getLocalizedSurahName(surah: Surah | undefined, locale?: string): string {
  if (!surah) return "";
  if (locale === "bn") {
    return BENGALI_SURAHS[surah.id]?.name ?? surah.name;
  }
  return surah.name;
}

export function getLocalizedSurahTranslation(surah: Surah | undefined, locale?: string): string {
  if (!surah) return "";
  if (locale === "bn") {
    return BENGALI_SURAHS[surah.id]?.translation ?? surah.translation;
  }
  return surah.translation;
}

const LOWER_BENGALI_RECITERS = new Map<string, string>();
for (const [key, val] of Object.entries(BENGALI_RECITERS)) {
  LOWER_BENGALI_RECITERS.set(key.toLowerCase().trim(), val);
}

export function getLocalizedReciterName(name: string, locale?: string): string {
  if (locale !== "bn") return name;
  const trimmed = name.trim();
  const direct = BENGALI_RECITERS[trimmed];
  if (direct) return direct;

  const lower = trimmed.toLowerCase();
  const fromLower = LOWER_BENGALI_RECITERS.get(lower);
  if (fromLower) return fromLower;

  const normKey = lower.replace(/[^a-z0-9]/g, " ").replace(/\s+/g, " ");
  for (const [k, v] of LOWER_BENGALI_RECITERS.entries()) {
    if (k.replace(/[^a-z0-9]/g, " ").replace(/\s+/g, " ") === normKey) {
      return v;
    }
  }

  const words = normKey.split(" ").filter((w) => w.length > 2 && w !== "al" && w !== "bin" && w !== "abu");
  if (words.length > 0) {
    for (const [k, v] of LOWER_BENGALI_RECITERS.entries()) {
      const kWords = k.replace(/[^a-z0-9]/g, " ").toLowerCase();
      if (words.every((w) => kWords.includes(w))) {
        return v;
      }
    }
  }

  return name;
}

